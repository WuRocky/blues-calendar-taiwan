import assert from 'node:assert/strict'
import fs from 'node:fs'

const hero = fs.readFileSync(new URL('../app/components/HomeHero.vue', import.meta.url), 'utf8')
const locales = ['zh-TW', 'en', 'ja', 'ko'].map(locale =>
  JSON.parse(fs.readFileSync(new URL(`../i18n/locales/${locale}.json`, import.meta.url), 'utf8'))
)

assert.match(hero, /const heroImageSrc = imageAssets\.heroTaipei101\.src/)
assert.match(hero, /:src="heroImageSrc"/)
assert.match(hero, /v-if="!imageFailed"/)
assert.match(hero, /@error="imageFailed = true"/)
assert.match(hero, /hero-media-fallback/)
assert.match(hero, /loading="eager"/)
assert.match(hero, /fetchpriority="high"/)
assert.match(hero, /width="2400"/)
assert.match(hero, /height="1601"/)
assert.match(hero, /:alt="\$t\('home\.heroImageAlt'\)"/)
assert.match(hero, /<NuxtLink class="bct-button hero-primary-action" :to="localePath\('calendar'\)"/)
assert.match(hero, /@media\(max-width:760px\)/)
assert.match(hero, /hero-content bct-container/)
assert.match(hero, /\.hero-content\{position:relative/)
assert.match(hero, /background:linear-gradient\(135deg,var\(--bct-bg-soft\),var\(--bct-surface-strong\)\)/)
assert.match(hero, /min-height:clamp\(430px,45vw,620px\)/)
assert.match(hero, /object-fit:cover;object-position:center 50%/)
assert.match(hero, /linear-gradient\(90deg,rgba\(19,48,72,\.74\)/)
assert.doesNotMatch(hero, /hero-copy\{[^}]*background:/)
assert.doesNotMatch(hero, /hero-copy\{[^}]*border:/)
assert.match(hero, /hero-secondary-action/)
assert.match(hero, /prefers-reduced-motion/)
assert.doesNotMatch(hero, /--color-/)
assert.doesNotMatch(hero, /carousel|slider|autoplay|hero-rhythm|hero-ring/i)
assert.ok(locales.every(messages => messages.home.heroImageAlt))
assert.ok(locales.every(messages => messages.images?.fallbackAlt))

const footer = fs.readFileSync(new URL('../app/components/AppFooter.vue', import.meta.url), 'utf8')
assert.doesNotMatch(footer, /pexels|photo-credit|Front-end Developer/i)
assert.ok(fs.existsSync(new URL('../public/images/hero/taipei-101-community.jpg', import.meta.url)))

console.log('Home Hero verification passed.')
